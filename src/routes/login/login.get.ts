import { FastifyInstance } from "fastify";
import fs from "fs";
import type { PrismaClient } from '../../../generated/prisma/client';
import path from "path";
import { generateJWT, parseBasicAuth } from "../../app/utils";
import bcrypt from "bcrypt";

export function login(fastify: FastifyInstance, prisma: PrismaClient) {
    fastify.get(
        '/login',
        {
            schema: {
                tags: ['Authentication'],
                summary: 'Login user',
                description: 'Authenticate user with username and password sent with HTTP Basic authentication, returns JWT token',
                headers: {
                    type: 'object',
                    properties: {
                        authorization: { type: 'string', description: 'Basic base64(username:password)' },
                    },
                    required: ['authorization'],
                },
                response: {
                    200: {
                        description: 'Login successful, returns JWT token',
                        type: 'object',
                        properties: {
                            success: { type: 'boolean' },
                            message: { type: 'string' },
                            profilePicture: {
                                type: 'string',
                                nullable: true,
                                description: 'Profile picture encoded in base64'
                            },
                        },
                    },
                    400: {
                        description: 'Missing username or password',
                        type: 'object',
                        properties: {
                            success: { type: 'boolean' },
                            message: { type: 'string' },
                        },
                    },
                    401: {
                        description: 'Invalid username or password',
                        type: 'object',
                        properties: {
                            success: { type: 'boolean' },
                            message: { type: 'string' },
                        },
                    },
                },
            },
        },
        async function handler(request, reply) {
            const credentials = parseBasicAuth(request.headers.authorization);
            const username = credentials?.username;
            const password = credentials?.password;

            if (!username || !password) {
                return reply.status(400).send({ success: false, message: 'Username and password are required' });
            }

            const user = await prisma.user.findUnique({
                where: { username },
            });

            if (!user || !(await bcrypt.compare(password, user.pswHash))) {
                return reply.status(401).send({ success: false, message: 'Invalid username or password' });
            }

            let profileImage = null;

            const profileImagePath = path.join(process.cwd(), 'data/profile_pictures/' + user.profileImage);

            if (user.profileImage && fs.existsSync(profileImagePath)) {
                try {
                    const data = fs.readFileSync(profileImagePath);
                    profileImage = `${data.toString('base64')}`;
                } catch (e) {
                    fastify.log.error(e, 'Failed to read profile image');
                }
            }

            const expire = new Date();
            expire.setMonth(expire.getMonth() + 1);

            const session = await prisma.session.create({
                data: {
                    username: user.username,
                    // Token is a UUIDv4 generated by Prisma Client
                    expire: expire
                }
            });

            return reply.send({
                success: true, message: JSON.stringify({
                    profileImage: profileImage,
                    token: session.token,
                    tokenExpire: session.expire,
                    jwt: generateJWT(user)
                })
            });
        },
    );
}
